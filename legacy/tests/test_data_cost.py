def test_annotated_constants_keep_downlink_small():
    src = (ROOT / "app" / "main.py").read_text(encoding="utf-8")
    m_w = re.search(r"ANNOTATED_MAX_WIDTH\s*=\s*(\d+)", src)
    m_q = re.search(r"ANNOTATED_JPEG_QUALITY\s*=\s*(\d+)", src)
    assert m_w and m_q, "annotated constants missing"
    width, quality = int(m_w.group(1)), int(m_q.group(1))
    assert (width, quality) == (960, 76), (
        f"annotated payload constants moved to {width}px/q{quality}; "
        "re-run scripts/build_replay.py and re-check IMPACT_EVIDENCE §4b "
        "against the 2 MB session budget before committing")
    # annotated_scale must derive from the constant, not a second literal.
    assert "ANNOTATED_MAX_WIDTH / image.shape[1]" in src


