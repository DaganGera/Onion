SW = (STATIC / "sw.js").read_text(encoding="utf-8") \
    if (STATIC / "sw.js").exists() else ""


def test_sw_exists_and_is_vanilla_js():
    assert SW, "app/static/sw.js missing"
    assert "import " not in SW.replace("self.importScripts", ""), \
        "no ES modules in the worker"
    assert "require(" not in SW, "no CommonJS either"
    assert re.search(r"CACHE_VERSION\s*=\s*'sama-", SW), "cache version missing"


def test_sw_never_touches_non_get_or_cross_origin_or_other_paths():
    assert "req.method !== 'GET'" in SW, "must ignore non-GET"
    assert "url.origin === self.location.origin" in SW, "must be same-origin only"
    assert "url.pathname.startsWith('/static/')" in SW
    assert re.search(r"\^\\/api\\/replay\\/\\d\+\$", SW), \
        "replay allowlist regex missing"
    # Exactly two respondWith calls, one per allowlisted family.
    assert SW.count("respondWith") == 2


def test_sw_is_parseable_javascript():
    node = shutil.which("node")
    if not node:
        pytest.skip("node not installed on this machine")
    r = subprocess.run([node, "--check", str(STATIC / "sw.js")],
                       capture_output=True, text=True)
    assert r.returncode == 0, f"sw.js syntax error:\n{r.stderr}"


def test_index_registers_worker_only_where_safe():
    idx = (STATIC / "index.html").read_text(encoding="utf-8")
    assert "'serviceWorker' in navigator" in idx
    assert "location.protocol === 'https:'" in idx, \
        "plain-HTTP LAN testing must skip registration"
    assert "location.hostname === 'localhost'" in idx
    assert ".catch(() => {})" in idx, "registration failure must be silent"


# --------------------------------------------------------------------------
# 4. Zero external subresources: protects the offline demo AND the budget
# --------------------------------------------------------------------------


ALLOWED_EXTERNAL_HREF_PREFIXES = (
    # User-initiated WhatsApp share NAVIGATION, not a loaded subresource;
    # nothing downloads unless the officer taps it.
    "https://wa.me/?text=",
)


@pytest.mark.parametrize("page", sorted(p.name for p in STATIC.glob("*.html")))
def test_no_external_subresource_in_any_page(page):
    html = (STATIC / page).read_text(encoding="utf-8")
    hits = re.findall(
        r"""(?:src|href)\s*=\s*["'](https?://[^"']+)["']""", html)
    # url(...) / @import in inline styles would also hit the wire:
    hits += re.findall(r"""url\(\s*['"]?(https?://[^)'"]+)""", html)
    hits += re.findall(r"""@import\s+['"]?(https?://[^;'"]+)""", html)
    bad = [h for h in hits
           if not any(h.startswith(p) for p in ALLOWED_EXTERNAL_HREF_PREFIXES)]
    assert not bad, f"{page} loads external resources: {bad}"
