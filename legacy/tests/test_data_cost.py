def test_uplink_is_measured_from_real_repo_photos(ie):
    dc = ie.data_cost()
    assert dc["n_photos"] >= 10, "uplink sample suspiciously small"
    assert dc["up_min_kb"] > 0 and dc["up_max_kb"] >= dc["up_median_kb"]
    # The client clamp must be mirrored from index.html's own constants...
    assert dc["upload_max_edge"] == 1600
    assert dc["jpeg_quality"] == 80


def test_downlink_measured_and_shrunk_by_a859(ie):
    dc = ie.data_cost()
    assert dc["n_replays"] == 6, "judge demo expects six cached replays"
    # A859 halved this from 276 KB; if it creeps back over ~200 KB the
    # sufficiency-sample session line below starts failing for real.
    assert dc["down_median_kb"] <= 200, (
        f"per-look downlink regressed to {dc['down_median_kb']} KB")


def test_every_modelled_session_stays_under_the_2mb_budget(ie):
    dc = ie.data_cost()
    sessions = [
        ("first visit, 2 looks", ie.session_cost_kb(dc, 2, first_visit=True)),
        ("repeat visit, 2 looks", ie.session_cost_kb(dc, 2, first_visit=False)),
        ("repeat visit, 6 looks", ie.session_cost_kb(dc, 6, first_visit=False)),
    ]
    for label, kb in sessions:
        assert kb <= SESSION_BUDGET_KB, (
            f"{label} costs {kb:.0f} KB — over the {SESSION_BUDGET_KB} KB "
            "session budget; shrink ANNOTATED_* or the shell before shipping")


